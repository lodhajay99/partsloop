#!/usr/bin/env node
/**
 * Concatenates every migration and the seed into one paste-ready file —
 * `npm run db:bundle`, output at supabase/bundle.sql.
 *
 * This is the escape hatch when a direct Postgres connection is not available:
 * new Supabase projects resolve their direct host over IPv6 only, plenty of
 * networks cannot reach it, and the pooler URI is easy to mix up with the REST
 * URL. Pasting one file into the dashboard's SQL editor needs no connection
 * string and no database password at all.
 *
 * Order matters and is the filename order, exactly as `db:push` would apply it.
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const migrationsDir = join(here, '..', 'supabase', 'migrations');
const seedFile = join(here, '..', 'supabase', 'seed.sql');
const outFile = join(here, '..', 'supabase', 'bundle.sql');

const migrations = readdirSync(migrationsDir)
  .filter((f) => f.endsWith('.sql'))
  .sort();

const parts = [
  `-- PartLoop: full schema + seed, generated by \`npm run db:bundle\`.
--
-- Paste the whole thing into the Supabase SQL editor and run it once.
-- Safe to re-run: the migrations are create-if-not-exists / create-or-replace,
-- and the seed truncates PartLoop's own five tables before rebuilding them.
--
-- Files included, in order:
${migrations.map((f) => `--   supabase/migrations/${f}`).join('\n')}
--   supabase/seed.sql
`,
];

for (const file of migrations) {
  parts.push(
    `\n-- ${'='.repeat(74)}\n-- ${file}\n-- ${'='.repeat(74)}\n`,
    readFileSync(join(migrationsDir, file), 'utf8').trimEnd(),
    '\n',
  );
}

parts.push(
  `\n-- ${'='.repeat(74)}\n-- seed.sql\n-- ${'='.repeat(74)}\n`,
  readFileSync(seedFile, 'utf8').trimEnd(),
  '\n',
);

const bundle = parts.join('');
writeFileSync(outFile, bundle, 'utf8');

console.log(`Wrote supabase/bundle.sql`);
console.log(`  ${migrations.length} migrations + seed`);
console.log(`  ${bundle.split('\n').length} lines, ${(bundle.length / 1024).toFixed(0)} KB`);
console.log('\nPaste it into: Supabase dashboard -> SQL Editor -> New query -> Run.');
